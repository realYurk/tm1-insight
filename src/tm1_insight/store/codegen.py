def _process_declaration(params: list[dict], source_type: str,
                         source_name: str, variables: list[str] | None = None) -> str:
    """生成「Process 声明」注释块：入参 / 数据源 / 变量，方便粘贴到 Architect 后对照配置。

    Architect 里这三样其实是通过 TI 编辑器的 Parameters / Data Source / Variables
    三个页签设置的，但粘贴纯代码时看不到，这里用注释清单列出来。
    """
    lines = [
        "#Region - Process Declaration (在 Architect 的对应页签里配置)",
        "",
        "### 1. 入参 (Parameters 页签) —— 按顺序添加，类型见注释",
    ]
    for prm in params:
        nm = prm.get("name", "?")
        dim = prm.get("dim")
        if nm == "pDoProcessLogging":
            lines.append(f"#   {nm:<24} String   (必填，'1'=启用日志)")
        elif nm == "pDebug":
            lines.append(f"#   {nm:<24} String   (调试开关，'1'=输出调试日志)")
        elif dim:
            lines.append(f"#   {nm:<24} String   (维度 {dim} 的元素，做 DIMIX 校验)")
        else:
            lines.append(f"#   {nm:<24} String   (业务入参)")
    if not params:
        lines.append("#   （无业务入参）")
    lines += [
        "",
        f"### 2. 数据源 (Data Source 页签) —— 类型 {source_type}",
        f"#   {source_name}",
        "",
        "### 3. 变量 (Variables 页签) —— 按数据源维度顺序，变量名取维度名（v 开头、首字母大写、无空格）",
        "###    （另含框架变量：vValue / sThisProcName / nErr / sErr 等，见 Declare Constants）",
    ]
    if variables:
        lines.append("###    数据源维度 → 变量映射：")
        for v in variables:
            lines.append(f"#      {_var_name(v)} = {v}")
    lines.append("#EndRegion - Process Declaration")
    lines.append("")
    return "\n".join(lines)


