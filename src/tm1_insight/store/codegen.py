def _as_literal(value: str) -> str:
    """把映射里的固定成员安全转为 TI 字符串字面量。

    调用方可能已经传入 "'X'"，此时校验引号闭合后原样使用；否则统一转义。
    """
    text = (value or '').strip()
    if len(text) >= 2 and text.startswith("'") and text.endswith("'"):
        inner = text[1:-1].replace("''", "'")
        return quote_member(inner)
    return quote_member(text)


def data_transfer(con: duckdb.DuckDBPyConnection, src_cube: str, tgt_cube: str,
                  prefix: str = "}APQ", src_filters: list[dict] | None = None,
                  tgt_filters: list[dict] | None = None,
                  params: list[dict] | None = None,
                  operation: str = "CellIncrementN",
                  src_dims: list[str] | None = None,
                  tgt_dims: list[str] | None = None,
                  dim_mapping: dict[str, dict] | None = None,
                  clear_policy: str = 'target_scope') -> dict:
    """生成「从源 cube 传输到目标 cube」的完整框架 TI 代码。

    参数：
      src_filters: 源视图筛选 [{dim, elems, kind}]（kind: param/const/blank）
      tgt_filters: 目标清空筛选 [{dim, elems, kind}]
      params: 入参定义 [{name, dim}]（dim 用于 Test parameters 校验）
      operation: data 段默认写操作（CellIncrementN/CellPutN/CellPutS）
      src_dims/tgt_dims: 显式维度顺序（用于尚未部署的设计草稿；为空则从快照读取）
      dim_mapping: 目标维度 → {'fixed': "'成员'" , 'source': 'vXxx'}，优先于同名自动对齐

    返回 dict：prolog/metadata/data/epilog/mapping/src_dims/tgt_dims/params/unmapped
    """
    p = _norm_prefix(prefix)
    if clear_policy not in ('target_scope', 'none'):
        raise ValueError('不支持的清空策略：%s' % clear_policy)
    src_dims = list(src_dims) if src_dims is not None else _cube_dims(con, src_cube)
    tgt_dims = list(tgt_dims) if tgt_dims is not None else _cube_dims(con, tgt_cube)
    src_vars, src_collisions = build_var_map(src_dims)
    tgt_vars, tgt_collisions = build_var_map(tgt_dims)

    # 维度对齐
    mapping: list[dict] = []
    for i, td in enumerate(tgt_dims):
        explicit = (dim_mapping or {}).get(td) or {}
        src_idx = src_dims.index(td) if (td in src_dims and not explicit) else None
        entry = {"tgt_dim": td, "tgt_idx": i, "src_idx": src_idx,
                 "auto": src_idx is not None}
        # 仅在显式映射时附加字段，保持旧响应结构不变
        if explicit.get("fixed"):
            entry["fixed"] = _as_literal(explicit["fixed"])
        if explicit.get("source"):
            entry["source"] = explicit["source"]
        mapping.append(entry)
    unmapped = [m["tgt_dim"] for m in mapping
                if not m["auto"] and not m.get("fixed") and not m.get("source")]

    # 入参（标准 2 个 + 业务入参）
    param_list = [{"name": "pDoProcessLogging", "dim": None},
                  {"name": "pDebug", "dim": None}]
    test_params: list[tuple] = []
    for prm in (params or []):
        param_list.append({"name": prm["name"], "dim": prm.get("dim")})
        if prm.get("dim"):
            test_params.append((prm["dim"], prm["name"]))

    # Prolog：Header + Process声明 + Initialize + Constants + Response + Debug + Test + ZeroOut + DataSource
    pl: list[str] = []
    pl.append(_header_block(f"Transfer data from {src_cube} to {tgt_cube}",
                            f"Cube: {src_cube}", p))
    pl.append("")
    pl.append(_process_declaration(
        param_list, "VIEW", f"cCubSrc = {src_cube}  (视图 cViewSrc)", src_dims))
    pl.append("#****Begin: Generated Statements***")
    pl.append("#****End: Generated Statements****")
    pl.append("")
    pl.append(_initialize_logging(p))
    pl.append("")
    pl.append("### Prolog script commences")
    pl.append("")
    pl.append(_declare_constants(src_cube, tgt_cube, p))
    pl.append("")
    pl.append(_log_response_message(p))
    pl.append("")
    if test_params:
        pl.append(_test_parameters(test_params))
        pl.append("")
    # 事务日志关闭 + ZeroOut + DataSource
    pl.append("### 关闭目标 cube 事务日志（提升批量写入性能）")
    pl.append("nLog = CubeGetLogChanges( cCubTgt );")
    pl.append("CubeSetLogChanges( cCubTgt, 0 );")
    pl.append("")
    if clear_policy == 'target_scope':
        pl.append(_zero_out(tgt_cube, tgt_filters or [], p))
    else:
        pl.append("### 清空策略：none —— 本次不生成任何 ZeroOut / 数据删除语句")
        pl.append("### 重复执行前请自行确认是否需要清理目标范围")
    pl.append("")
    pl.append(_create_datasource(src_cube, src_filters or [], "VIEW", p))
    pl.append("")
    pl.append("### END Prolog")
    prolog = "\n".join(pl)

    # Metadata：默认不处理业务，只保留一条日志计数语句
    md: list[str] = []
    md.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    md.append("IF( pDoProcessLogging @= '1' ); nMetadataRecordCount = nMetadataRecordCount + 1; EndIF;")
    md.append("sDebugFile = cDebugFile | '_Metadata.log';")
    md.append("### Logging - common script ---------------- END")
    md.append("")
    md.append("### Metadata script")
    md.append("### 默认不处理：变量映射逻辑统一放到 Data 段，此处留空。")
    md.append("# 如需在此做维度元素转换 / 跳过，取消注释后自行编写：")
    md.append("# vYear = '映射值';")
    md.append("# ItemSkip;")
    md.append("")
    md.append("### END Metadata")
    metadata = "\n".join(md)

    # Data：按目标 cube 完整维度列出变量并给默认填充值，用户直接改
    # 变量名用维度名（vYear/vCostCenter），源维度用同名变量映射
    dt: list[str] = []
    dt.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    dt.append("IF( pDoProcessLogging @= '1' );nDataRecordCount = nDataRecordCount + 1;EndIF;")
    dt.append("sDebugFile = cDebugFile | '_Data.log';")
    dt.append("### Logging - common script ---------------- END")
    dt.append("")
    dt.append("### Data script")
    dt.append("### 字段映射（按目标 cube 的维度顺序逐一赋值，直接修改右侧即可）")
    for m in mapping:
        var = tgt_vars[m["tgt_dim"]]
        if m.get("fixed"):
            dt.append(f"{var} = {m['fixed']};   # {m['tgt_dim']}: 固定成员")
        elif m.get("source"):
            dt.append(f"{var} = {m['source']};   # {m['tgt_dim']}: 来源映射")
        elif m["auto"]:
            src_var = src_vars[src_dims[m["src_idx"]]]
            dt.append(f"{var} = {src_var};")
        else:
            dt.append(f"{var} = '';   # {m['tgt_dim']}: 未映射，生成前必须补齐")
    dt.append("")
    dt.append("### Updating Cell（写入目标 cube 的完整维度交叉点）")
    args = ", ".join([tgt_vars[m["tgt_dim"]] for m in mapping])
    dt.append(f"{operation}(vValue, cCubTgt, {args});")
    dt.append("")
    dt.append("### END Data")
    data = "\n".join(dt)

    # Epilog
    el: list[str] = []
    el.append("### Err Handling")
    el.append("If(nErr <> 0); LogOutput('ERROR', sErr); ProcessQuit(); EndIf;")
    el.append("")
    el.append("# 恢复事务日志")
    el.append("CubeSetLogChanges( cCubTgt, nLog );")
    el.append("")
    el.append("# Clean Up（销毁临时视图）")
    el.append("If(ViewExists(cCubSrc, cViewSrc) <> 0); ViewDestroy(cCubSrc, cViewSrc); EndIf;")
    if clear_policy == 'target_scope':
        el.append("If(ViewExists(cCubTgt, cViewClr) <> 0); ViewDestroy(cCubTgt, cViewClr); EndIf;")
    el.append("")
    el.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    el.append("IF(pDoProcessLogging @= '1');")
    el.append("  nProcessFinishTime = Now(); sProcessErrorLogFile = GetProcessErrorFileName;")
    el.append("  CellPutN(nProcessFinishTime, sProcLogCube, sLogYear, sLogDay, sLogMinute, sLogSecond, sThisProcName, 'nProcessFinishTime');")
    el.append("  CellPutN(1, sProcLogCube, sLogYear, sLogDay, sLogMinute, sLogSecond, sThisProcName, 'nProcessCompletedFlag');")
    el.append("  CellPutN(nDataRecordCount, sProcLogCube, sLogYear, sLogDay, sLogMinute, sLogSecond, sThisProcName, 'nDataRecordCount');")
    el.append("  CellPutS(sProcessRunBy, sProcLogCube, sLogYear, sLogDay, sLogMinute, sLogSecond, sThisProcName, 'sRunBy');")
    el.append("  CellPutS(sProcLogParams, sProcLogCube, sLogYear, sLogDay, sLogMinute, sLogSecond, sThisProcName, 'sParams');")
    el.append("  IF(nDataRecordCount > 0);")
    el.append("    CellPutN(nProcessFinishTime, sCubLogCube, cCubTgt, 'nLastTimeUpdate');")
    el.append("    CellPutS(sThisProcName, sCubLogCube, cCubTgt, 'sProcess');")
    el.append("    CellPutS(sProcessRunBy, sCubLogCube, cCubTgt, 'sProcessRunBy');")
    el.append("  EndIF;")
    el.append("EndIF;")
    el.append("### Logging - common script ---------------- END")
    epilog = "\n".join(el)

    return {
        "src_cube": src_cube,
        "tgt_cube": tgt_cube,
        "src_dims": src_dims,
        "tgt_dims": tgt_dims,
        "mapping": mapping,
        "params": param_list,
        "unmapped": unmapped,
        "variables": dict(src=src_vars, target=tgt_vars),
        "collisions": src_collisions + tgt_collisions,
        "clear_policy": clear_policy,
        "prolog": prolog,
        "metadata": metadata,
        "data": data,
        "epilog": epilog,
    }


