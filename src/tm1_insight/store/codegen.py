def _test_parameters(params: list[str]) -> str:
    """参数校验块：对每个入参做 DIMIX 校验。params 是 (维度名, 参数变量名) 列表。"""
    if not params:
        return ""
    lines = ["#Region - Test parameters"]
    for dim, var in params:
        lines.append(f"sDim = '{dim}';")
        lines.append(f"IF( DIMIX( sDim,  {var}) = 0 );")
        lines.append("  nErr = nErr + 1;")
        lines.append(f"  sErr = sErr | IF( sErr @<> '', ' & ', '' ) | 'Element '| {var} | ' not found in Dimension: ' | sDim;")
        lines.append("EndIF;")
        lines.append("")
    lines += [
        "### If parameters fail validation then set data source to NULL",
        "IF( nErr > 0 );",
        "  IF( pDebug @>= '1' ); AsciiOutput( sDebugFile, sErr ); EndIF;",
        "  DataSourceType = 'NULL';",
        "  ItemReject( sErr );",
        "EndIF;",
        "#EndRegion - Test parameters",
    ]
    return "\n".join(lines)


def _build_filter(filters: list[dict]) -> str:
    """把筛选条件拼成 bedrock 的 pFilter 字符串。

    filters: [ {dim, elems: [..], kind: 'param'|'const'|'blank'} ]
    kind='param' 表示用入参变量（如 pYear）；'const' 表示字面量；'blank' 留空 TODO。
    返回 sFilter 赋值语句列表（list[str]）。
    """
    lines: list[str] = ["sFilter = '';"]
    for f in filters:
        dim = f["dim"]
        elems = f.get("elems") or []
        if f.get("kind") == "blank":
            lines.append(f"# TODO: {dim} 维度请填写筛选逻辑")
            lines.append(f"sFilter = sFilter | sDelimDim | '{dim}' | sDelimEleStart | '';")
            continue
        if f.get("kind") == "param":
            var = f.get("var")
            if not var:
                var = "p" + dim.replace(" ", "")
            lines.append(f"sFilter = sFilter | sDelimDim | '{dim}' | sDelimEleStart | {var};")
            continue
        # const：多个元素用 sDelimEle 连接
        if len(elems) == 1:
            lines.append(f"sFilter = sFilter | sDelimDim | '{dim}' | sDelimEleStart | '{elems[0]}';")
        else:
            body = " | sDelimEle | ".join(f"'{e}'" for e in elems)
            lines.append(f"sFilter = sFilter | sDelimDim | '{dim}' | sDelimEleStart | {body};")
    return "\n".join(lines)


