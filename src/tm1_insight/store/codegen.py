    lines.append("")
    lines.append("### 8. 建系统参数 cube（Sys Parameter，导出路径/当前期间等全局参数）")
    lines.append("# 注意：该 cube 命名固定为 Sys Parameter（cCubSysParam），不随日志前缀变化；")
    lines.append("# 数据导出 / 维度导出 TI 通过 CellGetS(cCubSysParam, 'Export Folder', 'Text') 取导出目录。")
    lines.append("sDim = 'Sys Parameter Measure';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Text') = 0); DimensionElementInsertDirect(sDim, '', 'Text', 'N'); EndIF;")
    lines.append("IF(DimIx(sDim, 'Numeric') = 0); DimensionElementInsertDirect(sDim, '', 'Numeric', 'N'); EndIF;")
    lines.append("")
    lines.append(f"sDim = '{o['sys_param_cube']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    for sp in SYS_PARAMS:
        lines.append(f"IF(DimIx(sDim, '{sp}') = 0); DimensionElementInsertDirect(sDim, '', '{sp}', IF(SubSt('{sp}', 1, 4) @= '>>>>', 'C', 'N')); EndIF;")
    lines.append("")
    lines.append("sCube = '" + o['sys_param_cube'] + "';")
    lines.append("IF(CubeExists(sCube) = 0);")
    lines.append(f"  CubeCreate(sCube, '{o['sys_param_cube']}', 'Sys Parameter Measure');")
    lines.append("EndIF;")
    lines.append("")
    init_pro = "\n".join(lines)

    # ---- ti_prolog：标准 TI 的 Prolog 日志骨架 ----
    pl: list[str] = []
    pl.append("#****Begin: Generated Statements***")
    pl.append("#****End: Generated Statements****")
    pl.append("")
    pl.append("#Region - Initialize Logging")
    pl.append("sThisProcName = GetProcessName(); sProcLogParams = '';")
    pl.append("### Params")
    pl.append("# sProcLogParams = Expand('pParam1:%pParam1% & pParam2:%pParam2% ...');")
    pl.append("### Params")
    pl.append("If( pDoProcessLogging @= '1' );")
    pl.append(f"  cCubTgt='';sProcLogCube='{o['log_cube']}';sCubLogCube='{o['last_cube']}';nProcessStartTime=Now();nProcessFinishTime=0;nMetaDataRecordCount=0;nDataRecordCount=0;")
    pl.append("  NumericGlobalVariable('PrologMinorErrorCount');PrologMinorErrorCount=0;NumericGlobalVariable('MetadataMinorErrorCount');MetadataMinorErrorCount=0;NumericGlobalVariable('DataMinorErrorCount');DataMinorErrorCount=0;NumericGlobalVariable('ProcessReturnCode');ProcessReturnCode=0;")
