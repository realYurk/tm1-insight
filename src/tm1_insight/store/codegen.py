def _zero_out(tgt_cube: str, filters: list[dict], prefix: str = "}APQ") -> str:
    """ZeroOut 块：bedrock.cube.data.clear 清目标。"""
    filter_code = _build_filter(filters) if filters else "sFilter = '';"
    lines = [
        "#Region - ZeroOut",
        "sProc = '}bedrock.cube.data.clear';",
        "# Set filter as per logic requirement of the ZeroOut",
        filter_code,
        "",
        "nRet = ExecuteProcess( sProc,",
        "  'pCube', cCubTgt,",
        "\t'pView', cViewClr,",
        "\t'pFilter', sFilter,",
        "\t'pDimDelim', sDelimDim,",
        "\t'pEleStartDelim', sDelimEleStart,",
        "\t'pEleDelim', sDelimEle,",
        "\t'pTemp', 1,",
        "\t'pLogOutput', nDebug",
        ");",
        "",
        "If( nRet <> ProcessExitNormal() );",
        "  nErr = nErr + 1;",
        "  sErr = sErr | IF( sErr @<> '', ' & ', '' ) | 'Error in ZeroOut.';",
        "  DataSourceType = 'NULL';",
        "  ItemReject( sErr );",
        "EndIf;",
        "#EndRegion - ZeroOut",
    ]
    return "\n".join(lines)


