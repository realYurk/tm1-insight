    lines.append("IF(CubeExists(sCube) = 0);")
    lines.append(f"  CubeCreate(sCube, '{o['year_dim']}', '{o['day_dim']}', '{o['minute_dim']}', '{o['second_dim']}', '{o['proc_dim']}', '{o['measure_dim']}');")
    lines.append("EndIF;")
    lines.append("")
