def dimension_maintain(dim: str, prefix: str = "}APQ") -> dict:
    """生成「维度维护」TI：新增元素 + 建层级 + 更新属性（完整框架）。"""
    p = _norm_prefix(prefix)

    pl: list[str] = []
    pl.append(_header_block(f"Maintain dimension {dim}", "Dimension subset", p))
    pl.append("")
    pl.append("#****Begin: Generated Statements***")
    pl.append("#****End: Generated Statements****")
    pl.append("")
    pl.append(_initialize_logging(p))
    pl.append("")
    pl.append("### Prolog script commences")
    pl.append("")
    pl.append(_declare_constants("", "", p))
    pl.append("")
    pl.append(_log_response_message(p))
    pl.append("")
    pl.append("# 目标维度")
    pl.append(f"sDim = '{dim}';")
    pl.append("")
    pl.append("### 数据源：维度子集（逐元素处理）")
    pl.append("DatasourceType             = 'SUBSET';")
    pl.append(f"DatasourceNameForServer    = '{dim}';")
    pl.append("DatasourceDimensionSubset  = 'All';")
    pl.append("")
    pl.append("### END Prolog")
    prolog = "\n".join(pl)

    md: list[str] = []
    md.append("### Metadata script")
    md.append("# 新增元素（若有父级则挂到父级下）")
    md.append("# IF(DimIx(sDim, vElement) = 0);")
    md.append("#   DimensionElementInsertDirect(sDim, '', vElement, 'N');")
    md.append("#   DimensionElementComponentAddDirect(sDim, vParent, vElement, 1);")
    md.append("# EndIF;")
    md.append("### END Metadata")
    metadata = "\n".join(md)

    dt: list[str] = []
    dt.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    dt.append("IF( pDoProcessLogging @= '1' );nDataRecordCount = nDataRecordCount + 1;EndIf;")
    dt.append("### Logging - common script ---------------- END")
    dt.append("")
    dt.append("### Data script")
    dt.append("IF(DimIx(sDim, vElement) = 0);")
    dt.append("  DimensionElementInsertDirect(sDim, '', vElement, 'N');")
    dt.append("EndIF;")
    dt.append("# 更新属性")
    dt.append("# AttrPutS(vAttrValue, sDim, vElement, 'AttrName');")
    dt.append("# AttrPutN(vAttrNum, sDim, vElement, 'AttrName');")
    dt.append("### END Data")
    data = "\n".join(dt)

    el: list[str] = []
    el.append("### Err Handling")
    el.append("If(nErr <> 0); LogOutput('ERROR', sErr); ProcessQuit(); EndIf;")
    el.append("")
    el.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    el.append("IF(pDoProcessLogging @= '1'); LogOutput('INFO', sThisProcName | ' finished'); EndIF;")
    el.append("### Logging - common script ---------------- END")
    epilog = "\n".join(el)

    return {
        "dim": dim,
        "prolog": prolog,
        "metadata": metadata,
        "data": data,
        "epilog": epilog,
    }
