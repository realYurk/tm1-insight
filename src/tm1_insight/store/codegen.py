    dt.append("  END;")
    dt.append("  TEXTOUTPUT(cExportFileName, Expand(sRow));")
    dt.append("ELSE;")
    dt.append("  j=1;")
    dt.append("  WHILE(j<=nParentNum);")
    dt.append("    vParent = ElPar(cDimSrc, vElement, j);")
    dt.append("    sRow = '%pQuote%%vElement%%pQuote%%pFieldDelim%%pQuote%%vParent%%pQuote%';")
    dt.append("    i=1;")
    dt.append("    WHILE(i<=nTotal);")
    dt.append("      sRow = sRow | '%pFieldDelim%%pQuote%%sValue0' | NumberToString(i) | '%%pQuote%';")
    dt.append("      i = i+1;")
    dt.append("    END;")
    dt.append("    TEXTOUTPUT(cExportFileName, Expand(sRow));")
    dt.append("    j=j+1;")
    dt.append("  END;")
    dt.append("ENDIF;")
    dt.append("")
    dt.append("### END Data")
    data = "\n".join(dt)

    # Epilog
    el: list[str] = []
    el.append("### Epilog script")
