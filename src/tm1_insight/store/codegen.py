def data_export(con: duckdb.DuckDBPyConnection, src_cube: str,
                prefix: str = "}APQ", src_filters: list[dict] | None = None,
                params: list[dict] | None = None) -> dict:
    """生成「从 cube 导出数据」的 TI 代码（CSV 导出，复刻真实 Sys.DWI.Data.Export.Cube）。"""
