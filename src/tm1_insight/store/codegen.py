def _cube_dims(con: duckdb.DuckDBPyConnection, cube: str) -> list[str]:
    """取 cube 的维度顺序列表。"""
    if not cube:
        return []
    return [r[0] for r in con.execute(
        "SELECT dimension_name FROM cube_has_dimension WHERE cube_name = ? ORDER BY dim_order",
        [cube],
    ).fetchall()]


def _norm_prefix(prefix: str) -> str:
    """规范化前缀：确保以 } 开头。"""
    p = (prefix or "}APQ").strip()
    if not p.startswith("}"):
        p = "}" + p
    return p


def _var_name(dim: str) -> str:
    """把维度名转成 TI 变量名：v 开头 + 首字母大写 + 去掉空格和非法字符。

    例：'Cost Center' -> 'vCostCenter'；'Business Line PPE' -> 'vBusinessLinePPE'。
    每个单词仅首字母转大写，其余字母保留原样（缩写如 PPE/PnL 保持大写）。
    """
    import re
    # 去掉 } 前缀（如 }Clients -> Clients）和各类非法字符
    cleaned = re.sub(r"[^A-Za-z0-9 ]", "", dim.lstrip("}"))
    words = cleaned.split()
    if not words:
        return "vValue"
    # 每个单词仅首字母大写，其余字符原样保留
    return "v" + "".join(w[0].upper() + w[1:] for w in words)


