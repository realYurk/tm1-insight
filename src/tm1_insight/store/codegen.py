    lines: list[str] = []
    lines.append(_banner("日志框架初始化 · 前缀 " + p))
    lines.append("# 第一次在新环境运行时执行本 TI，自动建好日志依赖对象；")
    lines.append("# 之后每个 TI 的日志代码即可正常写入（元素存在，不再报「写不进去」）。")
    lines.append("")

    lines.append("### 1. 建时间维度元素")
    lines.append(f"sDim = '{o['year_dim']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Years') = 0); DimensionElementInsertDirect(sDim, '', 'Total Years', 'C'); EndIF;")
    for y in range(time_year_start, time_year_end + 1):
        lines.append(f"IF(DimIx(sDim, '{y}') = 0); DimensionElementInsertDirect(sDim, '', '{y}', 'N'); DimensionElementComponentAddDirect(sDim, 'Total Years', '{y}', 1); EndIF;")
    lines.append("")
    lines.append(f"sDim = '{o['day_dim']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Year') = 0); DimensionElementInsertDirect(sDim, '', 'Total Year', 'C'); EndIF;")
    lines.append("IF(DimIx(sDim, 'D000') = 0); DimensionElementInsertDirect(sDim, '', 'D000', 'N'); EndIF;")
    lines.append("n = 1; While(n <= 12); sM = 'M' | NumberToStringEx(n, '00', '', ''); "
                 "IF(DimIx(sDim, sM) = 0); DimensionElementInsertDirect(sDim, '', sM, 'N'); EndIF; n = n + 1; End;")
    lines.append("")
    lines.append(f"sDim = '{o['minute_dim']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Day') = 0); DimensionElementInsertDirect(sDim, '', 'Total Day', 'C'); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Day Entry') = 0); DimensionElementInsertDirect(sDim, '', 'Total Day Entry', 'N'); EndIF;")
    lines.append("")
    lines.append(f"sDim = '{o['second_dim']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Minute') = 0); DimensionElementInsertDirect(sDim, '', 'Total Minute', 'C'); EndIF;")
    lines.append("IF(DimIx(sDim, 'Last Entry') = 0); DimensionElementInsertDirect(sDim, '', 'Last Entry', 'N'); EndIF;")
    lines.append("n = 0; While(n <= 59); sS = NumberToStringEx(n, '00', '', ''); "
                 "IF(DimIx(sDim, sS) = 0); DimensionElementInsertDirect(sDim, '', sS, 'N'); EndIF; n = n + 1; End;")
    lines.append("")
    lines.append("### 2. 建进程维度（TI 名会自动插入）")
    lines.append(f"sDim = '{o['proc_dim']}';")
    lines.append("IF(DimIx(sDim) = 0); DimensionCreate(sDim); EndIF;")
    lines.append("IF(DimIx(sDim, 'Total Processes') = 0); DimensionElementInsertDirect(sDim, '', 'Total Processes', 'C'); EndIF;")
    lines.append("")
    lines.append("### 3. 建度量维度")
