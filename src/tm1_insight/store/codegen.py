def data_export_dim(con: duckdb.DuckDBPyConnection, dim: str,
                    prefix: str = "}APQ", params: list[dict] | None = None) -> dict:
    """生成「维度导出」的 TI 代码（复刻真实 Sys.DWI.Data.Export.Dim）。

    数据源为维度子集（}bedrock.hier.sub.create），Data 段遍历元素 + 属性，
    用 TEXTOUTPUT 输出 element_id / parent_id / 各属性列。
    """
    p = _norm_prefix(prefix)

    param_list = [{"name": "pDoProcessLogging", "dim": None},
                  {"name": "pDebug", "dim": None}]
    test_params: list[tuple] = []
    for prm in (params or []):
        param_list.append({"name": prm["name"], "dim": prm.get("dim")})
        if prm.get("dim"):
            test_params.append((prm["dim"], prm["name"]))

    # Prolog
    pl: list[str] = []
    pl.append(_header_block(f"Export Dimension Data ( {dim} )", f"Dim: {dim}", p))
    pl.append("")
    pl.append(_process_declaration(
        param_list, "SUBSET", f"cDimSrc = {dim}  (子集 cSubSrc)"))
    pl.append("#****Begin: Generated Statements***")
    pl.append("#****End: Generated Statements****")
    pl.append("")
    pl.append(_initialize_logging(p))
    pl.append("")
    pl.append("### Prolog script commences")
    pl.append("")
    # 维度导出的 constants：用 cDimSrc，带 cCubSysParam
    pl.append("#Region - Declare Constants")
    pl.append("# Standard naming convention for source and target cubes/dimensions")
    pl.append(f"cDimSrc         = '{dim}';")
    pl.append(f"cCubSysParam    = 'Sys Parameter';")
    pl.append(f"cCubParam       = '{framework_objects(p)['settings_cube']}';")
    pl.append("sTimeStamp      = TimSt( Now, '\\Y\\m\\d\\h\\i\\s' );")
    pl.append("sRandomInt      = NumberToString( INT( RAND( ) * 1000 ));")
    pl.append("cSubSrcPrefix   = CellGetS( cCubParam, 'Std Datasource View Prefix', 'String' );")
    pl.append("cSubSrc         = cSubSrcPrefix | sThisProcName |'_'| sTimeStamp |'_'| sRandomInt;")
    pl.append("cDebugLoc       = CellGetS( cCubParam, 'Location: Debugging', 'String' );")
    pl.append("cDebugLoc       = cDebugLoc | IF( SubSt( cDebugLoc, Long( cDebugLoc ), 1 ) @<> '\\', '\\', '' );")
    pl.append("cDebugFile      = cDebugLoc | sThisProcName |'_'| sTimeStamp;")
    pl.append("sDebugFile      = cDebugFile | '_Prolog.log';")
    pl.append("nDebug          = StringToNumber( pDebug );")
    pl.append("sDelimList      = CellGetS( cCubParam, 'pDelim', 'String' );")
    pl.append("cBedrockTmp     = 1;")
    pl.append("nErr            = 0;")
    pl.append("sErr            = '';")
    pl.append("#EndRegion - Declare Constants")
    pl.append("")
    pl.append(_log_response_message(p))
    pl.append("")
    if test_params:
        pl.append(_test_parameters(test_params))
        pl.append("")
    pl.append("#Region - Constance & Variable Declaire")
    pl.append("cExportFilePath = CellGetS(cCubSysParam, 'Export Folder', 'Text');")
    pl.append("cExportFilePath = cExportFilePath | '\\dwi\\';")
    pl.append("cExportFileName = sThisProcName | '_' | sTimeStamp | '.csv';")
    pl.append("cExportFileName = cExportFilePath | cExportFileName;")
    pl.append("pQuote = '\"';")
    pl.append("pFieldDelim = ',';")
    pl.append("SetOutputCharacterSet( cExportFileName, 'TM1CS_UTF8' );")
    pl.append("nRecordCount = 0;")
    pl.append("#EndRegion - Constance & Variable Declaire")
    pl.append("")
    pl.append("#Region - Create DataSource")
    pl.append("# 数据源：维度子集（逐元素处理）")
    pl.append("sProc = '}bedrock.hier.sub.create';")
    pl.append("nRet = ExecuteProcess( sProc,")
    pl.append("    'pLogOutput', nDebug,")
    pl.append("    'pDim', cDimSrc,")
    pl.append("    'pHier', '',")
    pl.append("    'pSub', cSubSrc,")
    pl.append("    'pConsol', '',")
    pl.append("    'pAttr', '',")
    pl.append("    'pAttrValue', '',")
    pl.append("    'pLevelFrom', 0,")
    pl.append("    'pLevelTo', 999,")
    pl.append("    'pExclusions', '',")
    pl.append("    'pDelim', sDelimList,")
    pl.append("    'pAddToSubset', 1,")
    pl.append("    'pAlias', '',")
    pl.append("    'pTemp', cBedrockTmp")
    pl.append(");")
    pl.append("If( nRet <> ProcessExitNormal() );")
    pl.append("  nErr = nErr + 1;")
    pl.append("  sErr = sErr | IF( sErr @<> '', ' & ', '' ) | 'Error in source subset creation.';")
    pl.append("  DataSourceType = 'NULL';")
    pl.append("  ItemReject( sErr );")
    pl.append("EndIf;")
    pl.append("")
    pl.append("### Assign data source")
    pl.append("DatasourceType             = 'SUBSET';")
    pl.append("DatasourceNameForServer    = cDimSrc;")
    pl.append("DatasourceDimensionSubset  = cSubSrc;")
    pl.append("DatasourceAsciiDelimiter   = pFieldDelim;")
    pl.append("DatasourceAsciiQuoteCharacter = '';")
    pl.append("#EndRegion - Create DataSource")
    pl.append("")
    pl.append("### END Prolog")
    prolog = "\n".join(pl)

    # Metadata
    md: list[str] = []
    md.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    md.append("IF( pDoProcessLogging @= '1' ); nMetadataRecordCount = nMetadataRecordCount + 1; EndIF;")
    md.append("sDebugFile = cDebugFile | '_Metadata.log';")
    md.append("### Logging - common script ---------------- END")
    md.append("")
    md.append("### Metadata script")
    md.append("")
    md.append("### END Metadata")
    metadata = "\n".join(md)

    # Data：遍历元素 + 属性，输出 element_id / parent_id / 属性列
    dt: list[str] = []
    dt.append("### Logging - common script ---------------- START (" + p + " FRAMEWORK)")
    dt.append("IF( pDoProcessLogging @= '1' );nDataRecordCount = nDataRecordCount + 1;EndIf;")
    dt.append("sDebugFile = cDebugFile | '_Data.log';")
    dt.append("### Logging - common script ---------------- END")
    dt.append("")
    dt.append("### Data script")
    dt.append("### Record Count")
    dt.append("nRecordCount = nRecordCount + 1;")
    dt.append("SetOutputCharacterSet( cExportFileName, 'TM1CS_UTF8' );")
    dt.append("")
    dt.append("### Attributes（按需增删，属性名替换为你维度上的真实属性）")
    dt.append("sAttr01 = 'Department';  sValue01 = AttrS(cDimSrc, vElement, sAttr01);")
    dt.append("sAttr02 = 'Code';        sValue02 = AttrS(cDimSrc, vElement, sAttr02);")
    dt.append("sAttr03 = 'Short Desc';  sValue03 = AttrS(cDimSrc, vElement, sAttr03);")
    dt.append("sAttr04 = 'Description'; sValue04 = AttrS(cDimSrc, vElement, '描述');")
    dt.append("nTotal = 4;")
    dt.append("")
    dt.append("sTitle = '%pQuote%element_id%pQuote%%pFieldDelim%%pQuote%parent_id%pQuote%';")
    dt.append("i=1;")
    dt.append("WHILE(i<=nTotal);")
    dt.append("  sTitle = sTitle | '%pFieldDelim%%pQuote%%sAttr0' | NumberToString(i) | '%%pQuote%';")
    dt.append("  i = i+1;")
    dt.append("END;")
    dt.append("")
    dt.append("## Line 1: File Header information")
    dt.append("If( nRecordCount = 1 );")
    dt.append("  TEXTOUTPUT(cExportFileName, Expand(sTitle));")
    dt.append("ENDIF;")
    dt.append("")
    dt.append("nParentNum = ElParN(cDimSrc, vElement);")
    dt.append("IF(nParentNum=0);")
    dt.append("  sRow = '%pQuote%%vElement%%pQuote%%pFieldDelim%%pQuote%%pQuote%';")
    dt.append("  i=1;")
    dt.append("  WHILE(i<=nTotal);")
    dt.append("    sRow = sRow | '%pFieldDelim%%pQuote%%sValue0' | NumberToString(i) | '%%pQuote%';")
